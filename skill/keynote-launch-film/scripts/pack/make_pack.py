def main():
    os.makedirs(DST, exist_ok=True)
    files = {f.split('_')[0]: f for f in os.listdir(SRC) if f.endswith('.png')}
    lines = ['连盈 LY-600 宣传片 · 海螺图生视频清单', '=' * 40, '',
             '统一设置：模型 MiniMax-H3-Max（或 Hailuo 2.3）· 时长 6 秒 · 分辨率选最高 · 每个镜头上传对应图片作为首帧',
             '生成好的视频请命名为编号开头，例如「11_H1.mp4」，统一放进本文件夹里的「返回视频」文件夹，我会按编号自动对上。', '']
    for no, code, use, cam, prompt in SHOTS:
        name = f'{no}_{code}'
        short = use.split('：', 1)[-1].split('（')[0].replace(' → ', '到').replace(' ← ', '').replace('/', '-').replace('，', '_')
        d = os.path.join(DST, f'{name}_{short}')
        os.makedirs(d, exist_ok=True)
        ext = os.path.splitext(files[code])[1]
        shutil.copy2(os.path.join(SRC, files[code]), os.path.join(d, name + '_首帧' + ext))
        full = f'{prompt}{cam} {COMMON}'
        open(os.path.join(d, name + '_提示词.txt'), 'w', encoding='utf-8').write(
            f'用在哪：{use}\n\n首帧图片：{name}_首帧{ext}\n设置：MiniMax-H3-Max（或 Hailuo 2.3）· 6 秒 · 最高分辨率\n'
            f'生成后命名：{name}.mp4（放进上传包里的「返回视频」文件夹）\n\n提示词（复制下面这段）：\n{full}\n')
        lines += [f'【{name}】{use}', f'文件夹：{os.path.basename(d)}', f'提示词：{full}', '']
    open(os.path.join(DST, '00_提示词总清单.txt'), 'w', encoding='utf-8').write('\n'.join(lines))
    os.makedirs(os.path.join(DST, '返回视频'), exist_ok=True)
    os.makedirs(os.path.join(DST, '参考_不用生成'), exist_ok=True)
    for code in ('H0', 'P1'):
        shutil.copy2(os.path.join(SRC, files[code]), os.path.join(DST, '参考_不用生成', files[code]))
    print(len(SHOTS), 'shots ->', DST)


if __name__ == '__main__':
    main()
